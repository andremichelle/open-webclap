"""Writes the factory kits as a C header: make-kits.py's WAVs, 16-bit mono, in the slot order of ReBirth.dll's
resource ids: one machine's kit as factory_kit[]. Usage: embed.py <kits dir> <808|909> <out header>"""
import os, sys, wave

NAMES = {
    "808": ["BD", "SD1", "SD2", "SD3", "SD4", "SD5", "N1", "N2", "N3", "N4", "CB", "CH", "CL", "CP", "CY",
            "HC", "HT", "LC", "LT", "MA", "MC", "MT", "OH", "RS"],
    "909": ["bd1", "bd2", "bd3", "bd4", "sd1", "sd2", "sd3", "sd4", "sd5", "sdn1", "sdn2", "sdn3", "lt",
            "mt", "ht", "rs", "hc", "chh", "ohh", "ccy", "rcy"],
}
kits, machine, out = sys.argv[1], sys.argv[2], sys.argv[3]
lines = ["// generated by ports/openrb/kits/embed.py from ports/openrb/kits (see its README for the sources)",
         "#pragma once", "#include <stdint.h>", "",
         "struct FactorySample {const int16_t *audio; uint32_t frames;};", ""]
for names in [NAMES[machine]]:
    entries = []
    for i, name in enumerate(names):
        with wave.open(os.path.join(kits, machine, f"{name}.wav")) as w:
            assert w.getnchannels() == 1 and w.getsampwidth() == 2 and w.getframerate() == 44100, name
            data = w.readframes(w.getnframes())
        values = [int.from_bytes(data[k:k + 2], "little", signed=True) for k in range(0, len(data), 2)]
        lines.append(f"static const int16_t kit{machine}_{i}[{len(values)}] = {{")
        for k in range(0, len(values), 24):
            lines.append("    " + ",".join(str(v) for v in values[k:k + 24]) + ",")
        lines.append("};")
        entries.append(f"    {{kit{machine}_{i}, {len(values)}}},")
    lines += [f"static const FactorySample factory_kit[{len(names)}] = {{",
              *entries, "};", ""]
open(out, "w").write("\n".join(lines))
